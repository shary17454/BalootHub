import Foundation

/// فعل مضاعفة قانوني متاح للاعب معيّن في حالة المزايدة الحالية.
///
/// هذا النوع يمثل ما يسمح به المحرك الآن، لا ما يختاره الوكيل الآلي. وجوده يعطي
/// الواجهة والتدريب والاختبارات مصدر حقيقة واحدًا لحركات الدبل/ثري/فور/قهوة/قفل.
public enum LegalMultiplierAction: Codable, Sendable, Equatable, Hashable {
    /// تمرير حق التصعيد الحالي.
    case pass
    /// رفع المضاعف إلى المستوى المحدد، ويجب أن يكون المستوى التالي مباشرة.
    case raise(Multiplier)
    /// قفل المضاعفة الحالية ومنع أي تصعيد لاحق.
    case lock
}
